// Initialize PostgreSQL pool
try {
  pool = new Pool(connectionConfig);

  // Probe connection
  pool.connect((err, client, release) => {
    if (err) {
      console.warn(`[Database] PostgreSQL notice: ${err.message}.`);
      console.log('[Database] Active Mode: Hybrid Memory & PostgreSQL Sync ready.');
      isPgConnected = false;
    } else {
      isPgConnected = true;
      release();
      console.log(`[Database] Connected to PostgreSQL on ${connectionConfig.host}:${connectionConfig.port}/${connectionConfig.database}`);
    }
  });
} catch (e) {
  console.warn(`[Database] PostgreSQL init warning: ${e.message}`);
}

async function query(text, params) {
  if (isPgConnected && pool) {
    try {
      return await pool.query(text, params);
    } catch (err) {
      console.error('[Database PG Query Error]', err);
      throw err;
    }
  }
  return null;
}

